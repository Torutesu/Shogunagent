#!/usr/bin/env node
// Subtitles and the written script, derived from the same scene data the
// renderer draws. Run directly to refresh apps/video/SCRIPT.md:
//
//   node apps/video/scripts/captions.mjs --write   (or --check)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VIDEOS, LANGS, durationOf } from '../src/videos.js';

const plain = (text) => text.replace(/[*`]/g, '').replace(/\n/g, ' ');

export function cuesOf(video, lang) {
  const cues = [];
  let start = 0;
  for (const scene of video.scenes) {
    const list = scene.captions || [];
    list.forEach(([at, text], i) => {
      const next = list[i + 1];
      cues.push({ scene: scene.id, start: start + at, end: next ? start + next[0] : start + scene.dur - 0.1, text: plain(text[lang]) });
    });
    start += scene.dur;
  }
  return cues;
}

function stamp(seconds, separator) {
  const ms = Math.round(seconds * 1000);
  const pad = (n, width = 2) => String(n).padStart(width, '0');
  return `${pad(Math.floor(ms / 3600000))}:${pad(Math.floor(ms / 60000) % 60)}:${pad(Math.floor(ms / 1000) % 60)}${separator}${pad(ms % 1000, 3)}`;
}

export function subtitleFiles(video, lang) {
  const cues = cuesOf(video, lang);
  return {
    srt: cues.map((c, i) => `${i + 1}\n${stamp(c.start, ',')} --> ${stamp(c.end, ',')}\n${c.text}\n`).join('\n'),
    vtt: `WEBVTT\n\n${cues.map((c) => `${stamp(c.start, '.')} --> ${stamp(c.end, '.')}\n${c.text}\n`).join('\n')}`,
  };
}

const clock = (s) => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`;

export function scriptMarkdown() {
  const lines = ['# Video script', '', '<!-- Generated by `node apps/video/scripts/captions.mjs --write` from apps/video/src/*.js. Edit the scenes, not this file. -->', '',
    'Every line below is what the subtitle track says at that time. The explainers burn these lines into the picture; the launch film ships them as `.srt` / `.vtt` only. There is no voice-over: the lines are written so they can be read aloud as one.', ''];
  for (const video of VIDEOS) {
    lines.push(`## ${video.file} — ${video.title.en} / ${video.title.ja}`, '', `Length ${clock(durationOf(video))} · ${video.scenes.length} scenes`, '', '| Time | Scene | English | 日本語 |', '|---|---|---|---|');
    const en = cuesOf(video, 'en');
    const ja = cuesOf(video, 'ja');
    en.forEach((cue, i) => lines.push(`| ${clock(cue.start)} | \`${cue.scene}\` | ${cue.text} | ${ja[i].text} |`));
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'SCRIPT.md');
  const text = scriptMarkdown();
  if (process.argv.includes('--write')) {
    writeFileSync(file, text);
    console.log(`wrote ${path.relative(process.cwd(), file)} (${VIDEOS.length} videos, ${LANGS.length} languages)`);
  } else if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== text) {
      console.error('apps/video/SCRIPT.md is stale; run node apps/video/scripts/captions.mjs --write');
      process.exit(1);
    }
    console.log('SCRIPT.md is current');
  } else {
    process.stdout.write(text);
  }
}
